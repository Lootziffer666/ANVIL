package io.anvil.modules.target.web

import java.io.File

/**
 * Inputs are raw serialized JSON/refs, never typed models from other `:modules:*` — Target
 * may not import Acoustic/Scene/Gameplay/Interface per CLAUDE.md §3 ("modules darf NICHT
 * andere modules importieren").
 */
data class ToneJsRuntimeRequest(
    val preloadList: List<String>,
    val buses: List<String>,
    val debugStateInputs: List<String>,
    val manifestJson: String,
    val cueGraphJson: String,
)

data class ToneJsRuntimeWriteResult(
    val manifestPath: String,
    val cueGraphPath: String,
    val runtimePath: String,
)

/** Writes `audio/runtime.ts` + `audio/manifest.json` + `audio/cue-graph.json` (Gate G-02). */
class ToneJsRuntimeWriter {

    fun write(outputDir: File, request: ToneJsRuntimeRequest): ToneJsRuntimeWriteResult {
        val audioDir = File(outputDir, "audio").apply { mkdirs() }
        val manifestFile = File(audioDir, "manifest.json").apply { writeText(request.manifestJson) }
        val cueGraphFile = File(audioDir, "cue-graph.json").apply { writeText(request.cueGraphJson) }
        val runtimeFile = File(audioDir, "runtime.ts").apply { writeText(renderRuntimeTs(request)) }
        return ToneJsRuntimeWriteResult(manifestFile.path, cueGraphFile.path, runtimeFile.path)
    }

    private fun renderRuntimeTs(request: ToneJsRuntimeRequest): String = buildString {
        appendLine("// AUTO-GENERATED by ANVIL ToneJsRuntimeWriter (Gate G-02). Do not hand-edit.")
        appendLine("import * as Tone from \"tone\";")
        appendLine()
        appendLine("export const PRELOAD_LIST = ${jsonArray(request.preloadList)};")
        appendLine("export const BUSES = ${jsonArray(request.buses)};")
        appendLine("export const DEBUG_STATE_INPUTS = ${jsonArray(request.debugStateInputs)};")
        appendLine()
        appendLine("let started = false;")
        appendLine("const busGains: Record<string, Tone.Gain> = {};")
        appendLine("const debugState: Record<string, number> = {};")
        appendLine("const eventLog: string[] = [];")
        appendLine()
        appendLine("/** Must be called from a user gesture handler (click/tap) — never autoplay. */")
        appendLine("export async function startAudioRuntime(): Promise<void> {")
        appendLine("  if (started) return;")
        appendLine("  await Tone.start();")
        appendLine("  for (const bus of BUSES) {")
        appendLine("    busGains[bus] = new Tone.Gain(1).toDestination();")
        appendLine("  }")
        appendLine("  started = true;")
        appendLine("  eventLog.push(\"runtime-started\");")
        appendLine("}")
        appendLine()
        appendLine("/** Vertical layering: ramps a bus's gain toward [target] over [rampSeconds]. */")
        appendLine("export function setBusGain(bus: string, target: number, rampSeconds = 0.5): void {")
        appendLine("  busGains[bus]?.gain.rampTo(target, rampSeconds);")
        appendLine("  eventLog.push(`gain:\${bus}:\${target}`);")
        appendLine("}")
        appendLine()
        appendLine("/** Schedules [callback] on the next bar boundary using Tone.Transport (musical, not wall-clock). */")
        appendLine("export function onNextBar(callback: () => void): void {")
        appendLine("  Tone.Transport.scheduleOnce(callback, \"@1m\");")
        appendLine("}")
        appendLine()
        appendLine("/** One-shot stinger playback through the given bus. */")
        appendLine("export function playStinger(player: Tone.Player, bus: string): void {")
        appendLine("  player.connect(busGains[bus] ?? Tone.getDestination());")
        appendLine("  player.start();")
        appendLine("  eventLog.push(`stinger:\${bus}`);")
        appendLine("}")
        appendLine()
        appendLine("/** Debug hook for CUE audio proofs (test builds only) — see docs/GOLDEN_RUN_REPORT.md Gate H. */")
        appendLine("export const ANVIL_AUDIO = {")
        appendLine("  getDebugState: () => ({ ...debugState }),")
        appendLine("  setState: (name: string, value: number) => { debugState[name] = value; },")
        appendLine("  getEventLog: () => [...eventLog],")
        appendLine("};")
        appendLine()
        appendLine("/** Stops transport, disposes every bus gain node, clears state — call on scene teardown. */")
        appendLine("export function disposeAudioRuntime(): void {")
        appendLine("  Tone.Transport.stop();")
        appendLine("  for (const bus of Object.keys(busGains)) {")
        appendLine("    busGains[bus].dispose();")
        appendLine("    delete busGains[bus];")
        appendLine("  }")
        appendLine("  started = false;")
        appendLine("}")
    }

    private fun jsonArray(values: List<String>): String =
        values.joinToString(prefix = "[", postfix = "]") { "\"${it.replace("\"", "\\\"")}\"" }
}
